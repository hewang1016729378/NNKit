public extension UIColor {
    static var random:UIColor {
        get {
            let r = CGFloat(arc4random()%255)
            let g = CGFloat(arc4random()%255)
            let b = CGFloat(arc4random()%255)
            return UIColor(red: r/255.0, green: g/255.0, blue: b/255.0, alpha: 1.0)
        }
    }
    var image:UIImage {
        get {
            let rect = CGRect(x: 0, y: 0, width: 1, height: 1)
            UIGraphicsBeginImageContext(rect.size)
            if let context = UIGraphicsGetCurrentContext() {
                context.setFillColor(self.cgColor)
                context.fill(rect)
            }
            var result = UIImage()
            if let img = UIGraphicsGetImageFromCurrentImageContext() {
                result = img
            }
            UIGraphicsEndImageContext()
            return result
        }
    }
    convenience init(r : CGFloat, g : CGFloat, b : CGFloat) {
        self.init(red: r / 255.0, green: g / 255.0, blue: b / 255.0, alpha: 1.0)
    }
    convenience init(r: CGFloat, g: CGFloat, b: CGFloat, a: CGFloat) {
        self.init(red: r / 255.0, green: g / 255.0, blue: b / 255.0, alpha: a)
    }
}
public func UBColor(hex:Int) -> UIColor {
    return UIColor.init(r: CGFloat(((hex)>>16) & 0xFF), g:  CGFloat(((hex)>>8) & 0xFF), b: CGFloat((hex) & 0xFF))
}
public func UBColor(hex:Int, alpha:Float) -> UIColor {
    return UIColor.init(r: CGFloat(((hex)>>16) & 0xFF), g:  CGFloat(((hex)>>8) & 0xFF), b: CGFloat((hex) & 0xFF), a:CGFloat(alpha))
}


extension UIColor {
    open class var lineColor: UIColor {
        return "#EBEBEB".color()
    }
    public var hexString: String {
        let colorRef = cgColor.components
        let r = colorRef?[0] ?? 0
        let g = colorRef?[1] ?? 0
        let b = ((colorRef?.count ?? 0) > 2 ? colorRef?[2] : g) ?? 0
        let a = cgColor.alpha

        var color = String(
            format: "#%02lX%02lX%02lX",
            lroundf(Float(r * 255)),
            lroundf(Float(g * 255)),
            lroundf(Float(b * 255))
        )
        if a < 1 {
            color += String(format: "%02lX", lroundf(Float(a)))
        }
        return color
    }
}
